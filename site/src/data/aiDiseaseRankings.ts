function categoryKit(category: string) {
  return (
    categoryPrompts[category] ?? {
      focus: [
        'summarize the case precisely',
        'rank the most plausible next decisions',
        'identify missing information that would meaningfully change management',
      ],
      information: [
        'Exact diagnosis, severity, and current clinical question',
        'Timeline, prior treatments, current medications, and recent objective data',
        'Comorbidities, contraindications, and patient goals',
      ],
      output: [
        'Case summary',
        'Ranked options',
        'Missing data',
        'Monitoring and escalation plan',
      ],
    }
  );
}

function buildPrompt(ranking: DiseaseRanking) {
  const kit = categoryKit(ranking.category);
  return [
    `You are helping analyze a case of ${ranking.disease}.`,
    '',
    `Task: ${kit.focus.join('; ')}.`,
    '',
    'Instructions:',
    `1. Start by summarizing the case in a compact problem representation tailored to ${ranking.disease}.`,
    `2. Use the available data to explain the most important disease-specific drivers of outcome and why this problem is ranked highly for AI compute in this framework: ${ranking.why}`,
    '3. Rank the next best options or hypotheses rather than giving a single answer.',
    '4. Explicitly separate what is well supported from what is uncertain.',
    '5. Identify missing information/tests that would most change the ranking or recommendation.',
    '6. End with a practical action plan and monitoring plan.',
    '',
    'Return sections in this order:',
    ...kit.output.map((item, index) => `${index + 1}. ${item}`),
  ].join('\n');
}

function buildRequiredInformation(ranking: DiseaseRanking) {
  const kit = categoryKit(ranking.category);
  return [...universalInformation, ...kit.information];
}

function buildExpectedOutput(ranking: DiseaseRanking) {
  return categoryKit(ranking.category).output;
}

function withWorkflowKit(ranking: DiseaseRanking): DiseaseWorkflowKit {
  return {
    ...ranking,
    prompt: buildPrompt(ranking),
    requiredInformation: buildRequiredInformation(ranking),
    expectedOutput: buildExpectedOutput(ranking),
  };
}

export const top100DiseaseRankings: DiseaseWorkflowKit[] = diseaseRankings
  .slice(0, 100)
